#!/usr/bin/env node
/**
 * Generate canvas-light / canvas-dark CSS scoping classes for showcase canvases.
 *
 * Each /showcase/[slug] previews a real industry composition. The canvas
 * should default to light mode and offer a local toggle, independent of
 * the surrounding site's theme.
 *
 * The DS uses a `.dark` ancestor selector — so a child cannot truly escape
 * an ancestor `.dark` without re-declaring the variables that flip between
 * modes. This script reads primitives.css + semantic.css, identifies every
 * variable that has a dark-mode override, and emits two CSS classes:
 *
 *   .canvas-light  — locks subtree to light values
 *   .canvas-dark   — locks subtree to dark values
 *
 * The two classes can sit anywhere in the tree and override any ancestor
 * `.dark` cascade because CSS variables resolve at the nearest declaration.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const __filename = fileURLToPath(import.meta.url)
const here = dirname(__filename)
const repoRoot = resolve(here, '..', '..', '..')

const prim = readFileSync(join(repoRoot, 'packages/core/src/tokens/primitives.css'), 'utf8')
const sem = readFileSync(join(repoRoot, 'packages/core/src/tokens/semantic.css'), 'utf8')

/** Pull out everything between the matched `{` and its closing `}`. */
function extractBlock(content, startSelectorRegex) {
  const m = content.match(startSelectorRegex)
  if (!m) return null
  let i = content.indexOf('{', m.index)
  if (i === -1) return null
  const blockStart = i + 1
  let depth = 1
  while (depth > 0 && i < content.length - 1) {
    i++
    if (content[i] === '{') depth++
    else if (content[i] === '}') depth--
  }
  return content.slice(blockStart, i)
}

const lightPrim = extractBlock(prim, /^:root\s*\{/m) ?? ''
const darkPrim = extractBlock(prim, /^\.dark\s*\{/m) ?? ''
const lightSem = extractBlock(sem, /^:root\s*\{/m) ?? ''
const darkSem = extractBlock(sem, /^\.dark\s*\{/m) ?? ''

const varLineRe = /^\s*(--[\w-]+)\s*:\s*([^;]+);/gm

function collect(block) {
  const map = new Map()
  for (const m of block.matchAll(varLineRe)) {
    map.set(m[1], m[2].trim())
  }
  return map
}

const lightPrimVars = collect(lightPrim)
const darkPrimVars = collect(darkPrim)
const lightSemVars = collect(lightSem)
const darkSemVars = collect(darkSem)

const lightLookup = new Map([...lightPrimVars, ...lightSemVars])
const darkLookup = new Map([...lightPrimVars, ...lightSemVars, ...darkPrimVars, ...darkSemVars])

const flippedNames = new Set([...darkPrimVars.keys(), ...darkSemVars.keys()])

const lightLines = []
const darkLines = []
for (const name of flippedNames) {
  const lVal = lightLookup.get(name)
  const dVal = darkLookup.get(name)
  if (lVal) lightLines.push(`  ${name}: ${lVal};`)
  if (dVal) darkLines.push(`  ${name}: ${dVal};`)
}

const out = `/* Generated by apps/site/scripts/build-canvas-modes.mjs — do not edit by hand.
 * Re-run: pnpm -F site build:canvas-modes
 */
.canvas-light {
${lightLines.join('\n')}
}
.canvas-dark {
${darkLines.join('\n')}
}
`

const outPath = join(here, '..', 'app', 'canvas-modes.css')
writeFileSync(outPath, out)
console.log(`wrote ${outPath}`)
console.log(`  ${lightLines.length} light vars`)
console.log(`  ${darkLines.length} dark vars`)
