#!/usr/bin/env node
/**
 * propose-text-ramp.mjs  (codemod-ASSIST — reports, never mutates)
 *
 * Setu UI §3 wants typography via the semantic ramp (`text-body-*` / `text-heading-*`
 * / `text-label-*`, size+weight+leading+tracking bundled) instead of the size-only
 * `text-ds-*` utility. This scans every `text-ds-*` site and PROPOSES a ramp variant
 * per site from the surrounding class context, with a confidence, into a review file.
 *
 * It does NOT edit anything. Review the proposals, then apply high-confidence batches.
 * The map is not 1:1 (a `text-ds-sm` may be body / label / caption by role), which is
 * exactly why this is review-gated, not a blind find-replace.
 *
 * Usage (from packages/core/):
 *   node scripts/propose-text-ramp.mjs           # write review md + print summary
 *   node scripts/propose-text-ramp.mjs --json    # machine output
 */
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = join(HERE, '..')
const SRC = join(ROOT, 'src')
const SCAN_DIRS = ['ui', 'composed', 'shell', 'ai']
const AS_JSON = process.argv.includes('--json')

// text-ds-* size → ramp tier (body/label share tiers; headings for the big end).
// Values from tokens/semantic.css + typography-semantic.css.
const SIZE = {
  '2xs': { tier: 'xs', head: null },
  xs: { tier: 'xs', head: null },
  sm: { tier: 'sm', head: null },
  md: { tier: 'md', head: null },
  base: { tier: 'lg', head: null },
  lg: { tier: 'lg', head: 'xs' }, // 18px: body-lg is 16, heading-xs is 20 — ambiguous
  xl: { tier: null, head: 'sm' },
  '2xl': { tier: null, head: 'md' },
  '3xl': { tier: null, head: 'lg' },
  '4xl': { tier: null, head: 'xl' },
}

const TOKEN = /\btext-ds-([0-9a-z]+)\b/g

function scan(dir, files) {
  let entries
  try { entries = readdirSync(dir) } catch { return }
  for (const e of entries) {
    const p = join(dir, e)
    const s = statSync(p)
    if (s.isDirectory()) { scan(p, files); continue }
    if (!p.endsWith('.tsx')) continue
    if (/\.(test|stories)\.tsx$/.test(p)) continue
    files.push(p)
  }
}

function propose(sizeKey, ctx) {
  const spec = SIZE[sizeKey]
  if (!spec) return { variant: null, confidence: 'low', why: `unknown size text-ds-${sizeKey}` }
  const hasUpper = /\buppercase\b/.test(ctx)
  const hasBold = /font-(semibold|bold)/.test(ctx)
  const hasMuted = /text-surface-fg-(muted|subtle)/.test(ctx)

  // Headings: big sizes, or bold on a large-ish size.
  if (!spec.tier && spec.head) return { variant: `heading-${spec.head}`, confidence: 'high', why: 'display size' }
  if (spec.head && hasBold) return { variant: `heading-${spec.head}`, confidence: 'low', why: 'bold at 18px — heading-xs or body-lg?' }

  // Uppercase → the label ramp (its whole reason to exist).
  if (hasUpper) return { variant: `label-${spec.tier}`, confidence: 'high', why: 'uppercase → label ramp' }

  // Small + muted → likely caption/meta.
  if ((sizeKey === 'xs' || sizeKey === '2xs') && hasMuted) {
    return { variant: 'caption', confidence: 'low', why: 'small + muted — caption vs body-xs?' }
  }

  // Default: body ramp at the matched tier.
  const conf = spec.tier === 'lg' && sizeKey === 'lg' ? 'low' : 'high'
  return { variant: `body-${spec.tier}`, confidence: conf, why: conf === 'high' ? 'reading text' : '18px has no body tier' }
}

const files = []
for (const d of SCAN_DIRS) scan(join(SRC, d), files)

const rows = []
for (const file of files) {
  const rel = relative(ROOT, file).replace(/\\/g, '/')
  const lines = readFileSync(file, 'utf8').split('\n')
  lines.forEach((line, i) => {
    for (const m of line.matchAll(TOKEN)) {
      const size = m[1]
      const p = propose(size, line)
      rows.push({ file: rel, line: i + 1, from: `text-ds-${size}`, to: p.variant, confidence: p.confidence, why: p.why })
    }
  })
}

const byConf = { high: rows.filter((r) => r.confidence === 'high'), low: rows.filter((r) => r.confidence === 'low') }
const byVariant = rows.reduce((m, r) => ((m[r.to ?? '?'] = (m[r.to ?? '?'] || 0) + 1), m), {})

if (AS_JSON) {
  process.stdout.write(JSON.stringify({ total: rows.length, files: new Set(rows.map((r) => r.file)).size, byConf: { high: byConf.high.length, low: byConf.low.length }, byVariant, rows }, null, 2) + '\n')
  process.exit(0)
}

// Write review markdown
const outDir = join(ROOT, 'docs', 'audits')
mkdirSync(outDir, { recursive: true })
const out = join(outDir, 'type-ramp-proposals-2026-07.md')
let md = `# text-ds-* → ramp proposals (codemod-assist, review before applying)\n\n`
md += `Generated by \`scripts/propose-text-ramp.mjs\`. **Nothing is changed.** ${rows.length} sites across ${new Set(rows.map((r) => r.file)).size} files. High-confidence: ${byConf.high.length} · Low (needs a look): ${byConf.low.length}.\n\n`
md += `Proposed variants: ${Object.entries(byVariant).sort((a, b) => b[1] - a[1]).map(([k, n]) => `${k}=${n}`).join(' · ')}\n\n`
md += `## Low-confidence (review each)\n\n| File:line | From | Proposed | Why |\n|---|---|---|---|\n`
for (const r of byConf.low) md += `| ${r.file}:${r.line} | ${r.from} | ${r.to ?? '—'} | ${r.why} |\n`
md += `\n## High-confidence (safe to batch-apply after spot-check)\n\n| File:line | From | Proposed |\n|---|---|---|\n`
for (const r of byConf.high) md += `| ${r.file}:${r.line} | ${r.from} | ${r.to} |\n`
writeFileSync(out, md)

console.log(`\n  text-ds-* → ramp proposal`)
console.log(`  ${rows.length} sites · ${new Set(rows.map((r) => r.file)).size} files`)
console.log(`  high-confidence: ${byConf.high.length}   low (review): ${byConf.low.length}`)
console.log(`  variants: ${Object.entries(byVariant).sort((a, b) => b[1] - a[1]).map(([k, n]) => `${k}=${n}`).join('  ')}`)
console.log(`  → ${relative(ROOT, out).replace(/\\/g, '/')}\n`)
