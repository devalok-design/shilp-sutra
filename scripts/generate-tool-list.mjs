#!/usr/bin/env node
/**
 * generate-tool-list.mjs
 *
 * GENERATES the canonical MCP tool list from the single source of truth — the
 * `server.tool(name, description, …)` registrations in the MCP server — into
 * the docs that enumerate the surface, between managed markers:
 *
 *   <!-- BEGIN:mcp-tools --> … <!-- END:mcp-tools -->
 *
 * This replaces the old check-tool-list GATE. Instead of *checking* that a
 * hand-written list mentions every tool (a gate that only fails after the fact),
 * the list is DERIVED, so it is structurally impossible to omit or invent a
 * tool. `--check` re-generates and fails on drift (same model as the skill refs
 * / llms.txt), so a stale commit can't slip through.
 *
 *   node scripts/generate-tool-list.mjs           # write the block into targets
 *   node scripts/generate-tool-list.mjs --check    # exit 1 if any target is stale
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const ROOT = resolve(import.meta.dirname, '..')
const SERVER = join(ROOT, 'packages/mcp-server/src/index.mjs')
const TARGETS = ['packages/mcp-server/README.md', 'AGENTS.md']

// Category is curated (small, easy to maintain). A registered tool NOT listed
// here still appears under "Other" AND the generator warns — so completeness is
// guaranteed even if someone forgets to categorise a new tool.
const CATEGORY = {
  how_to_use: 'Reference',
  find_component: 'Reference', get_component: 'Reference', get_tokens: 'Reference',
  get_setup: 'Reference', upgrade: 'Reference', search_docs: 'Reference',
  detect_framework: 'Setup', preflight: 'Setup', validate_snippet: 'Setup', verify_setup: 'Setup',
  check_slop: 'Quality',
  report_issue: 'Write',
}
const ORDER = ['Reference', 'Setup', 'Quality', 'Write', 'Other']

function firstSentence(desc) {
  const s = desc.replace(/\s+/g, ' ').trim()
  // Sentence ends at .!? followed by whitespace + a capital (or EOL). Avoids
  // breaking on "e.g." / "i.e." (followed by a lowercase/quote, not a capital).
  const m = s.match(/^(.*?[.!?])(?=\s+[A-Z]|\s*$)/)
  let out = m ? m[1] : s
  if (out.length > 160) out = out.slice(0, 157).replace(/\s+\S*$/, '') + '…'
  return out
}

function parseTools(src) {
  const tools = []
  for (const m of src.matchAll(/server\.tool\(\s*['"]([a-z_]+)['"]\s*,\s*([\s\S]*?),\s*\{/g)) {
    const name = m[1]
    // description arg may be one string or several concatenated with `+`
    const literals = [...m[2].matchAll(/'((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)"/g)]
      .map((l) => (l[1] ?? l[2]).replace(/\\'/g, "'").replace(/\\"/g, '"'))
      .join('')
    tools.push({ name, desc: firstSentence(literals) })
  }
  return tools
}

const tools = parseTools(readFileSync(SERVER, 'utf-8'))
if (tools.length === 0) {
  console.error('generate-tool-list: parsed 0 tools — did the server.tool() shape change?')
  process.exit(1)
}

const uncategorised = tools.filter((t) => !CATEGORY[t.name])
for (const t of uncategorised) console.warn(`generate-tool-list: WARN ${t.name} has no category — listed under "Other". Add it to CATEGORY.`)

function render() {
  const groups = {}
  for (const t of tools) (groups[CATEGORY[t.name] || 'Other'] ??= []).push(t)
  const lines = [`<!-- BEGIN:mcp-tools --><!-- generated by scripts/generate-tool-list.mjs — do not edit by hand -->`]
  lines.push(`_${tools.length} tools (source: \`packages/mcp-server/src/index.mjs\`):_`)
  for (const cat of ORDER) {
    if (!groups[cat]?.length) continue
    lines.push('', `**${cat}:**`)
    for (const t of groups[cat].sort((a, b) => a.name.localeCompare(b.name))) lines.push(`- \`${t.name}\` — ${t.desc}`)
  }
  lines.push('<!-- END:mcp-tools -->')
  return lines.join('\n')
}

const block = render()
const MARKER = /<!-- BEGIN:mcp-tools -->[\s\S]*?<!-- END:mcp-tools -->/
const check = process.argv.includes('--check')
let drift = false

for (const rel of TARGETS) {
  const path = join(ROOT, rel)
  const cur = readFileSync(path, 'utf-8').replace(/\r\n/g, '\n')
  if (!MARKER.test(cur)) {
    console.error(`generate-tool-list: ${rel} has no <!-- BEGIN:mcp-tools --> … <!-- END:mcp-tools --> markers. Add them where the tool list should live.`)
    process.exit(1)
  }
  const next = cur.replace(MARKER, block)
  if (next === cur) {
    // already current
  } else if (check) {
    drift = true
    console.error(`generate-tool-list: DRIFT in ${rel} — run \`node scripts/generate-tool-list.mjs\` and commit.`)
  } else {
    writeFileSync(path, next)
    console.log(`generate-tool-list: wrote ${tools.length}-tool block into ${rel}`)
  }
}

if (check && drift) process.exit(1)
console.log(`generate-tool-list: ${check ? 'OK — all targets current' : 'done'} (${tools.length} tools)`)
